  const dictionaries = { fa, en }

  function normalizeLang(lang) {
    return lang === 'en' ? 'en' : 'fa'
  }

  function getLang() {
    return normalizeLang(localStorage.getItem(LANG_KEY) || 'fa')
  }

  function applyDocumentLang(lang) {
    const next = normalizeLang(lang)
    const dir = next === 'fa' ? 'rtl' : 'ltr'
    document.documentElement.setAttribute('lang', next)
    document.documentElement.setAttribute('dir', dir)
    document.documentElement.setAttribute('data-lang', next)
    return { lang: next, dir }
  }

  function setLang(lang, { reload = true } = {}) {
    const next = normalizeLang(lang)
    localStorage.setItem(LANG_KEY, next)
    applyDocumentLang(next)
    if (reload) {
      window.location.reload()
      return next
    }
    return next
  }

  function t(key) {
    const lang = getLang()
    const dict = dictionaries[lang] || fa
    return dict[key] || fa[key] || key
  }

  function locale() {
    return getLang() === 'en' ? 'en-US' : 'fa-IR'
  }

  applyDocumentLang(getLang())

  window.i18n = {
    t,
    getLang,
    setLang,
    applyDocumentLang,
    locale,
    LANG_KEY
  }
